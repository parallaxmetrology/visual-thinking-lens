"""
Rebuild skills/vtl/references/reference-ranges.md from fingerprints/*.csv.

Absolute cutoffs ("theta > 0.7 means directional") don't survive contact with
real images: most kernel values live in narrow bands. The skills read values
against these empirical percentiles instead. Rerun when fingerprints are added.

    python tools/reference_ranges.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "skills" / "vtl" / "references" / "reference-ranges.md"
COLS = ["delta_x", "delta_y", "r_v", "rho_r", "mu", "x_p", "theta", "d_s", "sdi",
        "gradient_floor_85", "gradient_ceiling_97", "tail_gap"]


def main():
    frames = [pd.read_csv(p).assign(set=p.stem) for p in sorted((ROOT / "fingerprints").glob("*.csv"))]
    df = pd.concat(frames, ignore_index=True)
    df = df[(df["valid"] == 1) & (df["mask_status"] != "FAIL")].copy()
    df["tail_gap"] = df["gradient_ceiling_97"] - df["gradient_floor_85"]
    q = df[COLS].quantile([0.05, 0.25, 0.5, 0.75, 0.95]).T
    sets = ", ".join(f"`{f['set'].iloc[0]}` ({len(f)})" for f in frames)
    modes = df["mask_mode"].value_counts(normalize=True)

    lines = [
        "# Reference ranges",
        "",
        f"Empirical percentiles of kernel `canon3-v8` over {len(df)} images: {sets}.",
        "Generated by `tools/reference_ranges.py`; rerun when fingerprints are added.",
        "",
        "Use these to say where a value sits (\"upper quartile of the reference set\"),",
        "not whether it's good. The reference mixes museum reproductions and AI images,",
        "so it is a yardstick, not a norm.",
        "",
        "| metric | p05 | p25 | p50 | p75 | p95 |",
        "|---|---|---|---|---|---|",
    ]
    for m, r in q.iterrows():
        fmt = "{:.1f}" if m == "rho_r" else "{:.4f}"
        lines.append(f"| `{m}` | " + " | ".join(fmt.format(v) for v in r.values) + " |")
    lines += [
        "",
        "Mask mode in the reference: "
        + ", ".join(f"{k} {v:.0%}" for k, v in modes.items()) + ".",
        "",
        "Notes:",
        "- `rho_r` sits near 100 × `mass_fraction` (about 12) whenever mass is spread across the",
        "  frame, because the convex hull then covers nearly everything. It rises only when",
        "  mass is confined to part of the frame, so read upward departures, not small wiggles.",
        "- `theta` is small for almost all real images; compare it relatively.",
        "- Most real images are `TEXTURE_FIELD`: placement and dispersion still apply, but",
        "  describe the structural field, not a discrete object.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
